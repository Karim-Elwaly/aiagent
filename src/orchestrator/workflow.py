"""
UAOS Temporal Workflow

The main orchestration workflow. Owns ALL execution state.
Temporal automatically persists every state change — if the worker
process crashes at any point, the workflow replays from its event
history and resumes exactly where it left off.

Architecture:
  - The workflow is a static topology: plan → route → execute → check → loop
  - The DAG Router is plain Python — domain-agnostic graph traversal
  - Human approval uses Temporal Signals (the workflow pauses consuming
    zero resources until a signal arrives)
  - Every activity has retry policies and timeouts
"""

from __future__ import annotations

import asyncio
import json
import logging
from datetime import timedelta
from typing import Any

from temporalio import workflow
from temporalio.common import RetryPolicy

# Activity stubs — imported at runtime to avoid sandbox issues
with workflow.unsafe.imports_passed_through():
    from src.core.config import get_settings
    from src.core.path_utils import extract_target_path
    from src.orchestrator.activities import (
        assemble_response,
        escalate_approval,
        evaluate_task_output,
        execute_task,
        notify_approval_required,
        plan_tasks,
        replan_tasks,
    )

logger = logging.getLogger(__name__)

# A ReAct loop makes up to worker_max_iterations LLM calls, so the budget covers all of them.
TASK_ACTIVITY_TIMEOUT_SECONDS = 900

TASK_RETRY_POLICY = RetryPolicy(
    maximum_attempts=3,
    initial_interval=timedelta(seconds=2),
    backoff_coefficient=2.0,
    # Deterministic failures repeat identically; only transient faults are worth retrying.
    non_retryable_error_types=[
        "ValueError",
        "ToolNotFoundError",
        "DAGValidationError",
        "ApprovalRejectedError",
    ],
)


@workflow.defn
class UAOSWorkflow:
    """The main UAOS orchestration workflow.

    Static topology, dynamic data. The workflow never changes shape —
    only the TaskDAG flowing through it is dynamic (generated by the LLM).

    Lifecycle:
      1. PLAN: Meta-Planner decomposes user query → TaskDAG
      2. ROUTE: Find tasks with all dependencies satisfied
      3. APPROVE: If task is HIGH/CRITICAL risk, pause for human signal
      4. EXECUTE: Universal Worker runs the task
      5. EVALUATE: Check result, decide next step
      6. LOOP: Back to ROUTE until all tasks done
      7. ASSEMBLE: Synthesize final response from all outputs
    """

    def __init__(self) -> None:
        self._approval_result: bool | None = None
        self._pending_task_name: str = ""
        self._pending_task_id: str = ""
        self._pending_task_desc: str = ""
        self._pending_task_risk: str = ""
        self._pending_task_params: dict[str, Any] = {}
        self._approval_guidance: str = ""
        self._approval_modified_params: dict[str, Any] = {}
        self._pending_tasks: dict[str, dict[str, Any]] = {}
        self._approvals: dict[str, dict[str, Any]] = {}
        self._dag_dict: dict[str, Any] = {}
        self._task_statuses: dict[str, str] = {}
        self._supervisor_evaluations: list[dict[str, Any]] = []
        self._result: dict[str, Any] | None = None

    @workflow.signal
    async def approve_task(self, payload: bool | dict[str, Any]) -> None:
        """Human sends approval/rejection for a high-risk task.

        Accepts either a boolean (legacy/direct) or a dictionary:
          {"approved": bool, "guidance": str, "modified_params": dict, "task_id": str}
        """
        if isinstance(payload, bool):
            resp = {"approved": payload, "guidance": "", "modified_params": {}}
            target_tid = next(iter(self._pending_tasks.keys()), self._pending_task_id)
        elif isinstance(payload, dict):
            resp = {
                "approved": payload.get("approved", False),
                "guidance": payload.get("guidance", ""),
                "modified_params": payload.get("modified_params", {}),
            }
            target_tid = payload.get("task_id") or next(iter(self._pending_tasks.keys()), self._pending_task_id)
        else:
            resp = {"approved": False, "guidance": "", "modified_params": {}}
            target_tid = next(iter(self._pending_tasks.keys()), self._pending_task_id)

        if target_tid:
            self._approvals[target_tid] = resp

        self._approval_result = resp["approved"]
        self._approval_guidance = resp["guidance"]
        self._approval_modified_params = resp["modified_params"]

        status_text = "APPROVED" if resp["approved"] else "REJECTED"
        try:
            workflow.logger.info(
                "Received approval signal: %s for task '%s' (guidance: '%s')",
                status_text,
                target_tid or self._pending_task_name,
                resp["guidance"][:50] if resp["guidance"] else "none",
            )
        except Exception:
            logger.info(
                "Received approval signal: %s for task '%s'",
                status_text,
                target_tid or self._pending_task_name,
            )

    @workflow.signal
    async def submit_clarification(self, payload: dict[str, Any]) -> None:
        """Receive operator clarification response for ambiguous task context."""
        cid = payload.get("clarification_id", "default")
        try:
            workflow.logger.info(
                "Received clarification signal for %s: %s",
                cid,
                payload.get("answer", "")[:50],
            )
        except Exception:
            logger.info("Received clarification signal for %s", cid)

    @workflow.query
    def get_status(self) -> dict[str, Any]:
        """Query current workflow status (available via Temporal API)."""
        first_pending_id = next(iter(self._pending_tasks.keys()), "")
        first_pending = self._pending_tasks.get(first_pending_id, {})
        return {
            "pending_task": first_pending.get("name", self._pending_task_name),
            "pending_task_id": first_pending_id or self._pending_task_id,
            "pending_task_desc": first_pending.get("description", self._pending_task_desc),
            "pending_task_risk": first_pending.get("risk_level", self._pending_task_risk),
            "pending_task_params": first_pending.get("parameters", self._pending_task_params),
            "awaiting_approval": len(self._pending_tasks) > 0
            or (self._approval_result is None and self._pending_task_name != ""),
            "pending_tasks": list(self._pending_tasks.values()),
            "dag": self._dag_dict,
            "task_statuses": self._task_statuses,
            "supervisor_evaluations": self._supervisor_evaluations,
            "result": self._result,
        }

    @workflow.run
    async def run(
        self,
        user_query: str,
        agent_id: str = "",
        custom_dag: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        """Main workflow execution entry point.

        Args:
            user_query: The raw user request.
            agent_id: Optional AgentProfile ID to steer persona and restrict tools.
            custom_dag: Optional user-defined TaskDAG to execute directly without auto-planning.

        Returns:
            Dict with 'response', 'tasks_completed', 'tasks_failed',
            and 'replans' counts.
        """
        workflow.logger.info(
            "Starting UAOS workflow for: %s (agent_id: %s, custom_dag: %s)",
            user_query[:100],
            agent_id or "default",
            "yes" if custom_dag else "no",
        )

        # ── Phase 1: Plan ────────────────────────────────
        if custom_dag and custom_dag.get("tasks"):
            workflow.logger.info(
                "Using user-defined custom TaskDAG with %d tasks",
                len(custom_dag["tasks"]),
            )
            dag_dict = custom_dag
        else:
            dag_dict = await workflow.execute_activity(
                plan_tasks,
                args=[user_query, agent_id],
                start_to_close_timeout=timedelta(seconds=180),
                retry_policy=RetryPolicy(
                    maximum_attempts=3,
                    initial_interval=timedelta(seconds=2),
                    backoff_coefficient=2.0,
                ),
            )

        target_path = extract_target_path(user_query)
        if target_path:
            workflow.logger.info("Detected target investigation path: %s", target_path)
            for t in dag_dict.get("tasks", []):
                params = t.setdefault("parameters", {})
                if "target_path" not in params:
                    params["target_path"] = target_path
                if "[Investigation Target Path]" not in t.get("description", ""):
                    t["description"] = f"{t.get('description', '')}\n\n[Investigation Target Path]: {target_path}"

        self._dag_dict = dag_dict
        self._task_statuses = {t["id"]: "pending" for t in dag_dict.get("tasks", [])}

        completed: dict[str, str] = {}  # task_id → output
        failed: dict[str, str] = {}  # task_id → error
        replan_count = 0
        max_replans = 2

        # ── Phase 2: Execute DAG ─────────────────────────
        while True:
            # Fast-fail any downstream tasks whose dependencies have failed
            self._cascade_failed_dependencies(dag_dict, completed, failed)

            # Route: find tasks with all dependencies satisfied
            ready_tasks = self._get_ready_tasks(dag_dict, completed, failed)

            if not ready_tasks:
                all_task_ids = {t["id"] for t in dag_dict["tasks"]}
                resolved_ids = set(completed.keys()) | set(failed.keys())

                if resolved_ids >= all_task_ids:
                    # All tasks processed
                    workflow.logger.info(
                        "All tasks processed: %d completed, %d failed",
                        len(completed),
                        len(failed),
                    )
                    break

                # Deadlocked: remaining tasks depend on failed ones
                if replan_count < max_replans:
                    workflow.logger.info(
                        "DAG deadlocked. Triggering re-plan (%d/%d)",
                        replan_count + 1,
                        max_replans,
                    )
                    dag_dict = await workflow.execute_activity(
                        replan_tasks,
                        args=[user_query, completed, failed],
                        start_to_close_timeout=timedelta(seconds=180),
                        retry_policy=RetryPolicy(maximum_attempts=2),
                    )
                    # Keep completed results, clear failures for the new plan
                    failed.clear()
                    replan_count += 1
                    continue
                else:
                    workflow.logger.warning(
                        "Max replans reached. Proceeding with partial results."
                    )
                    break

            # Execute ready tasks in parallel batches (respecting concurrency limit)
            settings = get_settings()
            max_concurrent = max(1, getattr(settings, "temporal_max_concurrent_activities", 3))

            pipeline_aborted = False
            for i in range(0, len(ready_tasks), max_concurrent):
                batch = ready_tasks[i : i + max_concurrent]
                if len(batch) == 1:
                    aborted = await self._execute_single_task_flow(
                        batch[0], completed, failed, agent_id, user_query, dag_dict
                    )
                    if aborted:
                        pipeline_aborted = True
                        break
                else:
                    workflow.logger.info(
                        "⚡ Executing batch of %d independent tasks in parallel: %s",
                        len(batch),
                        [t["id"] for t in batch],
                    )
                    results = await asyncio.gather(*[
                        self._execute_single_task_flow(
                            t, completed, failed, agent_id, user_query, dag_dict
                        )
                        for t in batch
                    ])
                    if any(results):
                        pipeline_aborted = True
                        break

            if pipeline_aborted:
                for t in dag_dict.get("tasks", []):
                    tid = t["id"]
                    if tid not in completed and tid not in failed:
                        self._task_statuses[tid] = "aborted"
                        failed[tid] = "Aborted due to upstream circuit breaker"
                break

        # ── Phase 3: Assemble Final Response ─────────────
        if not completed:
            self._result = {
                "response": (
                    "I was unable to complete any tasks for your request. "
                    f"Errors: {json.dumps(failed)}"
                ),
                "tasks_completed": 0,
                "tasks_failed": len(failed),
                "replans": replan_count,
            }
            return self._result

        final_response = await workflow.execute_activity(
            assemble_response,
            args=[user_query, dag_dict, completed],
            start_to_close_timeout=timedelta(seconds=120),
            retry_policy=RetryPolicy(maximum_attempts=2),
        )

        self._result = {
            "response": final_response,
            "tasks_completed": len(completed),
            "tasks_failed": len(failed),
            "replans": replan_count,
            "supervisor_evaluations": self._supervisor_evaluations,
        }
        return self._result

    async def _execute_single_task_flow(
        self,
        task_dict: dict[str, Any],
        completed: dict[str, str],
        failed: dict[str, str],
        agent_id: str,
        user_query: str,
        dag_dict: dict[str, Any],
    ) -> bool:
        """Executes a single task within the workflow lifecycle.

        Handles:
          1. Human approval gate (if HIGH or CRITICAL risk)
          2. Task execution activity (with heartbeat checkpointing & retry policy)
          3. Supervisor evaluation & automatic retry
          4. Circuit breaker abort detection

        Returns:
            bool: True if pipeline should abort immediately, False otherwise.
        """
        task_id = task_dict["id"]
        task_name = task_dict.get("name", task_id)
        risk_level = str(task_dict.get("risk_level", "low")).lower()

        # ── Approval Gate ────────────────────────────────
        if risk_level in ("high", "critical"):
            self._pending_tasks[task_id] = task_dict
            self._pending_task_name = task_name
            self._pending_task_id = task_id
            self._pending_task_desc = task_dict.get("description", "")
            self._pending_task_risk = risk_level
            self._pending_task_params = task_dict.get("parameters", {})
            self._task_statuses[task_id] = "awaiting_approval"

            # Notify subscribers
            try:
                await workflow.execute_activity(
                    notify_approval_required,
                    args=[task_dict],
                    start_to_close_timeout=timedelta(seconds=60),
                    retry_policy=RetryPolicy(maximum_attempts=2),
                )
            except Exception as notify_err:
                workflow.logger.warning(
                    "Failed to emit approval notification for '%s': %s", task_id, notify_err
                )

            approval_timeout = task_dict.get("approval_timeout_seconds") or 900
            workflow.logger.info(
                "Task '%s' (%s) requires approval (risk: %s). Pausing for signal (timeout: %ds)...",
                task_name,
                task_id,
                risk_level,
                approval_timeout,
            )

            try:
                await workflow.wait_condition(
                    lambda: task_id in self._approvals or (len(self._pending_tasks) <= 1 and self._approval_result is not None),
                    timeout=timedelta(seconds=approval_timeout),
                )
                resp = self._approvals.pop(task_id, None)
                if resp is None:
                    resp = {
                        "approved": self._approval_result if self._approval_result is not None else False,
                        "guidance": self._approval_guidance,
                        "modified_params": self._approval_modified_params,
                    }
                    self._approval_result = None
                    self._approval_guidance = ""
                    self._approval_modified_params = {}

                self._pending_tasks.pop(task_id, None)

                if not resp.get("approved", False):
                    workflow.logger.warning("Task '%s' was rejected by operator", task_name)
                    self._task_statuses[task_id] = "rejected"
                    failed[task_id] = f"Task rejected by operator. Guidance: {resp.get('guidance', 'None')}"
                    return False

                if resp.get("guidance"):
                    task_dict["description"] = (
                        f"{task_dict.get('description', '')}\n\n"
                        f"[OPERATOR GUIDANCE]: {resp['guidance']}"
                    )
                if resp.get("modified_params"):
                    task_dict.setdefault("parameters", {}).update(resp["modified_params"])

            except asyncio.TimeoutError:
                workflow.logger.warning(
                    "Task '%s' (%s) approval timed out after %ds",
                    task_name,
                    task_id,
                    approval_timeout,
                )
                self._pending_tasks.pop(task_id, None)
                try:
                    await workflow.execute_activity(
                        escalate_approval,
                        args=[task_dict, user_query],
                        start_to_close_timeout=timedelta(seconds=60),
                        retry_policy=RetryPolicy(maximum_attempts=2),
                    )
                except Exception as esc_err:
                    workflow.logger.warning("Escalation activity failed: %s", esc_err)

                self._task_statuses[task_id] = "failed"
                failed[task_id] = f"Approval timed out after {approval_timeout}s"
                return False

        # ── Execution Phase ──────────────────────────────
        task_dict["_user_query"] = user_query
        try:
            task_dict["_workflow_id"] = workflow.info().workflow_id
        except Exception:
            task_dict["_workflow_id"] = f"workflow-{task_id}"

        self._task_statuses[task_id] = "running"
        workflow.logger.info(
            "Executing task '%s' (%s), risk: %s",
            task_name,
            task_id,
            risk_level,
        )

        try:
            result_dict = await workflow.execute_activity(
                execute_task,
                args=[task_dict, dict(completed), agent_id],
                start_to_close_timeout=timedelta(seconds=TASK_ACTIVITY_TIMEOUT_SECONDS),
                retry_policy=TASK_RETRY_POLICY,
                heartbeat_timeout=timedelta(seconds=120),
            )
        except Exception as exc:
            err_msg = str(exc)
            if hasattr(exc, "cause") and exc.cause:
                err_msg = f"{exc.cause}"
            workflow.logger.error("Activity execute_task failed for '%s': %s", task_name, err_msg)
            self._task_statuses[task_id] = "failed"
            failed[task_id] = err_msg
            return False

        # ── Supervisor Evaluation & Retry Phase ───────────
        if result_dict.get("status") == "completed":
            task_output = result_dict.get("output", "")

            try:
                supervisor_eval = await workflow.execute_activity(
                    evaluate_task_output,
                    args=[task_dict, task_output, user_query, dict(completed)],
                    start_to_close_timeout=timedelta(seconds=120),
                    retry_policy=RetryPolicy(maximum_attempts=2),
                )
                if supervisor_eval:
                    decision = supervisor_eval.get("decision", "pass")
                    feedback = supervisor_eval.get("feedback", "")

                    if decision == "abort":
                        workflow.logger.warning(
                            "Circuit breaker triggered by supervisor on task '%s': %s",
                            task_name,
                            feedback,
                        )
                        self._supervisor_evaluations.append(supervisor_eval)
                        self._task_statuses[task_id] = "aborted"
                        failed[task_id] = f"Aborted by supervisor: {feedback}"
                        return True

                    elif decision in ("needs_retry", "need_more_info", "retry"):
                        workflow.logger.info(
                            "Supervisor requested retry for task '%s': %s",
                            task_name,
                            feedback,
                        )
                        self._supervisor_evaluations.append(supervisor_eval)
                        retry_task_dict = dict(task_dict)
                        retry_task_dict["description"] = (
                            f"{retry_task_dict.get('description', '')}\n\n"
                            f"[SUPERVISOR EVALUATION FEEDBACK - PLEASE GATHER MORE INFO]: {feedback}"
                        )
                        retry_result = await workflow.execute_activity(
                            execute_task,
                            args=[retry_task_dict, dict(completed), agent_id],
                            start_to_close_timeout=timedelta(seconds=TASK_ACTIVITY_TIMEOUT_SECONDS),
                            retry_policy=TASK_RETRY_POLICY,
                            heartbeat_timeout=timedelta(seconds=120),
                        )
                        if retry_result.get("status") == "completed":
                            task_output = retry_result.get("output", "")
                            result_dict = retry_result
                            self._supervisor_evaluations = [
                                e for e in self._supervisor_evaluations
                                if e.get("task_id") != task_id
                            ] + [{
                                "task_id": task_id,
                                "task_name": task_name,
                                "decision": "pass",
                                "confidence": 0.98,
                                "feedback": "Factual findings verified on supervisor retry.",
                            }]
                    else:
                        self._supervisor_evaluations.append(supervisor_eval)
            except Exception as eval_err:
                workflow.logger.warning(
                    "Supervisor evaluation error on '%s': %s", task_name, eval_err
                )

            completed[task_id] = task_output
            self._task_statuses[task_id] = "completed"
        else:
            self._task_statuses[task_id] = "failed"
            failed[task_id] = result_dict.get("error", "Task execution failed")

        return False

    def _get_ready_tasks(
        self,
        dag_dict: dict,
        completed: dict[str, str],
        failed: dict[str, str],
    ) -> list[dict]:
        """Generic DAG traversal. Domain-agnostic.

        Returns tasks whose dependencies are ALL in the completed set.
        This function does not know what the tasks ARE — it only
        examines the dependency graph structure.
        """
        resolved = set(completed.keys()) | set(failed.keys())
        ready = []

        for task in dag_dict.get("tasks", []):
            task_id = task["id"]

            # Skip already-processed tasks
            if task_id in resolved:
                continue

            # Check all dependencies are completed (not just resolved —
            # we need successful completion, not failure)
            deps = task.get("dependencies", [])
            deps_met = all(d in completed for d in deps)

            if deps_met:
                ready.append(task)

        return ready

    def _cascade_failed_dependencies(
        self,
        dag_dict: dict,
        completed: dict[str, str],
        failed: dict[str, str],
    ) -> bool:
        """Fast-fail downstream tasks whose required dependencies have failed.

        Traverses the DAG and marks any task with failed dependencies as skipped.
        Returns True if any new task status was cascaded.
        """
        changed = False
        resolved = set(completed.keys()) | set(failed.keys())
        for task in dag_dict.get("tasks", []):
            task_id = task["id"]
            if task_id in resolved:
                continue
            deps = task.get("dependencies", [])
            failed_deps = [d for d in deps if d in failed]
            if failed_deps:
                dep_names = ", ".join(failed_deps)
                failed[task_id] = f"Skipped: Required upstream dependency ({dep_names}) failed or was skipped."
                self._task_statuses[task_id] = "skipped"
                resolved.add(task_id)
                changed = True
                workflow.logger.info(
                    "Fast-failing task '%s' (%s) due to failed upstream dependencies: %s",
                    task.get("name", task_id),
                    task_id,
                    dep_names,
                )
        return changed
