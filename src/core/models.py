"""
UAOS Core Data Models

Defines all shared data structures used across the system:
- Task, TaskDAG, TaskResult — the execution plan and results
- RiskLevel, TaskStatus — enums for state management
- ToolSpec — tool registration metadata
"""

from __future__ import annotations

import json
from enum import Enum

from pydantic import BaseModel, Field

# ─── Enums ────────────────────────────────────────────────────────


class RiskLevel(str, Enum):
    """Risk classification for tasks and tools.
    HIGH and CRITICAL trigger human approval gates.
    """

    LOW = "low"  # auto-execute, read-only operations
    MEDIUM = "medium"  # auto-execute with logging, writes data
    HIGH = "high"  # requires human approval, modifies systems
    CRITICAL = "critical"  # always requires approval, irreversible


class TaskStatus(str, Enum):
    """Lifecycle status of a task within a DAG execution."""

    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    SKIPPED = "skipped"


# ─── Task & DAG Models ───────────────────────────────────────────


class Task(BaseModel):
    """A single atomic unit of work in the execution DAG.

    Tasks declare abstract skill requirements (e.g., 'web_search'),
    NOT specific tool names. The ToolRegistry resolves skills to
    concrete tools at runtime.
    """

    id: str = Field(description="Unique task identifier, e.g. 't1', 't2'")
    name: str = Field(description="Short human-readable task name")
    description: str = Field(
        description="Detailed instructions for the Universal Worker Agent"
    )
    required_skills: list[str] = Field(
        description=(
            "Abstract skill names needed for this task, "
            "e.g. ['web_search', 'summarization']"
        )
    )
    expected_output: str = Field(
        default="",
        description="Description of what this task should produce",
    )
    dependencies: list[str] = Field(
        default_factory=list,
        description="IDs of tasks that must complete before this one starts",
    )
    risk_level: RiskLevel = Field(
        default=RiskLevel.LOW,
        description="Risk classification — HIGH/CRITICAL trigger approval gates",
    )
    max_retries: int = Field(
        default=2,
        description="Maximum retry attempts on failure",
    )
    timeout_seconds: int = Field(
        default=300,
        description="Maximum execution time in seconds",
    )


class TaskDAG(BaseModel):
    """The complete execution plan generated by the Meta-Planner.

    Contains a list of tasks with dependency relationships forming
    a Directed Acyclic Graph. The DAG Router uses this to determine
    execution order — it never inspects task content, only the
    dependency structure.
    """

    goal: str = Field(description="The user's objective, restated clearly")
    reasoning: str = Field(description="Why this decomposition was chosen")
    tasks: list[Task]

    def get_ready_tasks(
        self, completed: set[str], failed: set[str]
    ) -> list[Task]:
        """Return tasks whose dependencies are ALL in the completed set.

        This is the core DAG routing algorithm. It is domain-agnostic —
        it only examines the graph structure, never the task content.
        """
        resolved = completed | failed
        return [
            task
            for task in self.tasks
            if task.id not in resolved
            and all(dep in completed for dep in task.dependencies)
        ]

    def get_task_by_id(self, task_id: str) -> Task | None:
        """Look up a task by its ID."""
        for task in self.tasks:
            if task.id == task_id:
                return task
        return None

    def validate_integrity(self) -> None:
        """Check for missing dependency references and cycles.

        Raises ValueError if the DAG is malformed.
        """
        task_ids = {t.id for t in self.tasks}

        # Check all dependency references exist
        for task in self.tasks:
            for dep in task.dependencies:
                if dep not in task_ids:
                    raise ValueError(
                        f"Task '{task.id}' depends on unknown task '{dep}'. "
                        f"Known tasks: {task_ids}"
                    )

        # Check for cycles via topological sort (Kahn's algorithm)
        in_degree = {t.id: len(t.dependencies) for t in self.tasks}
        queue = [tid for tid, deg in in_degree.items() if deg == 0]
        visited = 0

        while queue:
            current = queue.pop(0)
            visited += 1
            for task in self.tasks:
                if current in task.dependencies:
                    in_degree[task.id] -= 1
                    if in_degree[task.id] == 0:
                        queue.append(task.id)

        if visited != len(self.tasks):
            raise ValueError(
                "Circular dependency detected in TaskDAG. "
                "Tasks cannot depend on each other in a cycle."
            )

    def to_serializable(self) -> dict:
        """Convert to a plain dict for Temporal activity arguments."""
        return json.loads(self.model_dump_json())

    @classmethod
    def from_serializable(cls, data: dict) -> TaskDAG:
        """Reconstruct from a plain dict (e.g., from Temporal)."""
        return cls.model_validate(data)


# ─── Task Result ─────────────────────────────────────────────────


class TaskResult(BaseModel):
    """Output of a single task execution by a Universal Worker Agent."""

    task_id: str
    status: TaskStatus
    output: str = Field(default="", description="The task's output content")
    error: str | None = Field(
        default=None, description="Error message if status is FAILED"
    )
    tool_calls_made: list[str] = Field(
        default_factory=list,
        description="Names of tools that were called during execution",
    )
    execution_time_ms: int | None = Field(
        default=None,
        description="Wall-clock execution time in milliseconds",
    )

    def to_serializable(self) -> dict:
        """Convert to a plain dict for Temporal."""
        return json.loads(self.model_dump_json())

    @classmethod
    def from_serializable(cls, data: dict) -> TaskResult:
        """Reconstruct from a plain dict."""
        return cls.model_validate(data)


# ─── Supervisor Evaluation ───────────────────────────────────────


class SupervisorEvaluation(BaseModel):
    """Evaluation generated by the Supervisor LLM after a task/phase finishes."""

    decision: str = Field(
        default="accurate",
        description="'accurate' to proceed, or 'needs_retry' if data is missing or inaccurate",
    )
    confidence: float = Field(
        default=0.9,
        description="Confidence score between 0.0 and 1.0",
    )
    feedback: str = Field(
        default="",
        description="Specific feedback or missing details to guide the worker on retry",
    )
    missing_info: list[str] = Field(
        default_factory=list,
        description="Key pieces of evidence, parameters, or artifacts that were missing",
    )

    def to_serializable(self) -> dict:
        return json.loads(self.model_dump_json())

    @classmethod
    def from_serializable(cls, data: dict) -> SupervisorEvaluation:
        return cls.model_validate(data)

