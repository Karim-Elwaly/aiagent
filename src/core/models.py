class SupervisorEvaluation(BaseModel):
    """Evaluation generated by the Supervisor LLM after a task/phase finishes."""

    decision: str = Field(
        default="accurate",
        description="'accurate' to proceed, or 'needs_retry' if data is missing or inaccurate",
    )
    confidence: float = Field(
        default=0.9,
        description="Confidence score between 0.0 and 1.0",
    )
    feedback: str = Field(
        default="",
        description="Specific feedback or missing details to guide the worker on retry",
    )
    missing_info: list[str] = Field(
        default_factory=list,
        description="Key pieces of evidence, parameters, or artifacts that were missing",
    )

    def to_serializable(self) -> dict:
        return json.loads(self.model_dump_json())

    @classmethod
    def from_serializable(cls, data: dict) -> SupervisorEvaluation:
        return cls.model_validate(data)


