"""
UAOS Universal Worker Agent

A blank-slate executor with a custom ReAct (Reasoning + Acting) loop
built specifically for local LLM reliability. Every worker instance is
identical at creation — differentiated ONLY by runtime-injected persona
and tools.

The worker is created per-task and destroyed after execution.
No state leaks between tasks. No memory of previous work.

5 Guardrails for Local LLM Reliability:
  1. MAX ITERATIONS — stops infinite reasoning loops
  2. TOOL NAME VALIDATION — catches hallucinated tool names
  3. OUTPUT SIZE CAPPING — prevents context window overflow
  4. IMPLICIT FINAL ANSWER — handles LLMs that forget the protocol
  5. TIMEOUT PER TASK — prevents hung LLM calls
"""

from __future__ import annotations

import ast
import asyncio
import json
import logging
import os
import re
import time
from collections.abc import Callable
from typing import Any

from src.core.llm_client import LocalLLMClient
from src.core.models import Task, TaskResult, TaskStatus
from src.registry.tool_registry import ToolSpec

logger = logging.getLogger(__name__)


class UniversalWorkerAgent:
    """A blank-slate agent with a guarded ReAct loop.

    Born empty — configured at runtime with persona + tools.
    Created per-task, destroyed after execution. No state leaks.

    The ReAct loop:
      1. Send persona + conversation history to LLM
      2. Parse response for tool calls or final answer
      3. If tool call → validate → execute → append result → loop
      4. If final answer → return
      5. If max iterations hit → force return with what we have
    """

    def __init__(
        self,
        llm: LocalLLMClient,
        max_iterations: int = 8,
        max_output_chars: int = 2000,
        run_id: str = "",
    ):
        """
        Args:
            llm: The local LLM client for inference.
            max_iterations: Maximum ReAct loop iterations before forced stop.
                Prevents infinite reasoning loops. Default: 8.
            max_output_chars: Maximum chars per tool output. Prevents
                context window overflow from large tool results. Default: 2000.
            run_id: Investigation run identifier used to scope the evidence
                store. Injected into tools that declare ``needs_run_context``;
                never exposed to the LLM.
        """
        self.llm = llm
        self.max_iterations = max_iterations
        self.max_output_chars = max_output_chars
        self.run_id = run_id

    async def execute(
        self,
        task: Task,
        persona: str,
        tools: list[ToolSpec],
        upstream_context: dict[str, str] | None = None,
        user_query: str = "",
        on_token: Callable[[str], None] | None = None,
        on_event: Callable[[dict[str, Any]], None] | None = None,
        on_heartbeat: Callable[[], None] | None = None,
    ) -> TaskResult:
        """Execute a single task via the guarded ReAct loop.

        Args:
            task: The task to execute.
            persona: System prompt from PersonaSynthesizer.
            tools: Resolved concrete tools from ToolRegistry.
            upstream_context: Optional {task_id: output} from prior tasks.
            user_query: Optional overall user request containing target paths and goals.
            on_token: Optional callback for streaming tokens.
            on_event: Optional callback for tool/task lifecycle events.
            on_heartbeat: Optional callback to pulse liveness/heartbeat to orchestrator.

        Returns:
            TaskResult with status, output, and metadata.
        """
        start_time = time.monotonic()
        tool_map = {t.name: t for t in tools}
        tool_calls_made: list[str] = []

        # Construct clear user message containing task instructions, target context, and upstream context
        user_parts = []
        if user_query and user_query.strip():
            user_parts.append(f"# Overall User Request / Target Context:\n{user_query.strip()}")
        user_parts.append(f"# Task to Execute\n**{task.name}**\n\n{task.description}")

        if task.expected_output and task.expected_output.strip():
            user_parts.append(f"**Expected Output:**\n{task.expected_output}")

        if upstream_context:
            context_blocks = []
            for uid, uout in upstream_context.items():
                context_blocks.append(f"### Output from Prior Task `{uid}`:\n{uout}")
            user_parts.append(
                "# Context and Data from Previous Tasks:\n"
                "The following data was generated by preceding workflow tasks. Use it directly to perform your task:\n\n"
                + "\n\n".join(context_blocks)
            )

        if tools:
            tool_names = [t.name for t in tools]
            user_parts.append(
                f"# Execution Directive:\n"
                f"Use the available tools ({', '.join(tool_names)}) to inspect real telemetry and host environment data. "
                f"Execute the appropriate tool now."
            )

        user_content = "\n\n".join(user_parts)

        # Conversation history for the ReAct loop
        messages: list[dict[str, str]] = [
            {"role": "system", "content": persona},
            {"role": "user", "content": user_content},
        ]

        logger.info(
            "Worker starting task '%s' (%s) with %d tools, max %d iterations",
            task.name,
            task.id,
            len(tools),
            self.max_iterations,
        )

        for iteration in range(1, self.max_iterations + 1):
            logger.debug(
                "Task '%s' iteration %d/%d",
                task.id,
                iteration,
                self.max_iterations,
            )

            if on_heartbeat:
                try:
                    on_heartbeat()
                except Exception:
                    pass

            # ── Step 1: LLM thinks ──────────────────────────
            active_messages = self._compress_context_history(messages)
            openai_tools = self._convert_tools_to_openai(tools) if tools else None
            try:
                if on_token and not openai_tools:
                    # Stream tokens only when no tools are needed (tools require
                    # non-streaming chat() to receive atomic function-calling payloads)
                    tokens_list: list[str] = []
                    async for token in self.llm.chat_stream(active_messages):
                        tokens_list.append(token)
                        on_token(token)
                    response = "".join(tokens_list)
                else:
                    # Use non-streaming chat() when tools are available so the LLM
                    # receives the OpenAI function-calling schema and can return
                    # native tool_calls in the response.
                    try:
                        response = await asyncio.wait_for(
                            self.llm.chat(active_messages, tools=openai_tools),
                            timeout=task.timeout_seconds,
                        )
                    except TypeError:
                        response = await asyncio.wait_for(
                            self.llm.chat(active_messages),
                            timeout=task.timeout_seconds,
                        )
                    # Fire on_token with full response for UI streaming feedback
                    if on_token and response:
                        on_token(response)
                if not isinstance(response, str):
                    response = str(response)
            except TimeoutError:
                elapsed = int((time.monotonic() - start_time) * 1000)
                logger.warning(
                    "Task '%s' LLM call timed out at iteration %d",
                    task.id,
                    iteration,
                )
                return TaskResult(
                    task_id=task.id,
                    status=TaskStatus.FAILED,
                    output="",
                    error=f"LLM call timed out after {task.timeout_seconds}s",
                    tool_calls_made=tool_calls_made,
                    execution_time_ms=elapsed,
                )
            except Exception as e:
                elapsed = int((time.monotonic() - start_time) * 1000)
                logger.error(
                    "Task '%s' LLM call failed: %s", task.id, e
                )
                return TaskResult(
                    task_id=task.id,
                    status=TaskStatus.FAILED,
                    output="",
                    error=f"LLM call failed: {e}",
                    tool_calls_made=tool_calls_made,
                    execution_time_ms=elapsed,
                )

            def _get_accumulated_tool_outputs() -> str:
                tool_outputs: list[str] = []
                for msg in messages:
                    if msg["role"] == "user" and " returned:\n\n" in msg["content"]:
                        content = msg["content"]
                        body = content.split(" returned:\n\n", 1)[1]
                        if "\n\nAnalyze this result" in body:
                            body = body.split("\n\nAnalyze this result", 1)[0].strip()
                        if body:
                            tool_outputs.append(body)
                return "\n\n---\n\n".join(tool_outputs)

            # ── Step 2: Extract tool call ───────────────────
            tool_call = self._extract_tool_call(response)

            # If tools are available for this task and no tool has been executed yet,
            # we MUST NOT exit prematurely on early iterations.
            # Instead, steer the model directly to call a tool with concrete task arguments.
            if tool_call is None and tools and not tool_calls_made and iteration < (self.max_iterations - 1):
                logger.info(
                    "Task '%s' iteration %d produced no tool call; steering model to execute available tools",
                    task.id,
                    iteration,
                )
                messages.append({"role": "assistant", "content": response})
                steering_msg = self._build_tool_steering_message(task, tools, user_query)
                messages.append({"role": "user", "content": steering_msg})
                continue

            # ── Step 3: Check for explicit completion ───────
            final = self._extract_final_answer(response)
            if final is not None and final.strip():
                # Guardrail: If tools are provided and none have been executed yet,
                # reject premature conclusions and force the agent to use its tools first
                if tools and not tool_calls_made and iteration < (self.max_iterations - 1):
                    logger.info(
                        "Task '%s' attempted final answer without executing tools; steering to execute tools",
                        task.id,
                    )
                    messages.append({"role": "assistant", "content": response})
                    steering_msg = self._build_tool_steering_message(task, tools, user_query)
                    messages.append({"role": "user", "content": steering_msg})
                    continue

                elapsed = int((time.monotonic() - start_time) * 1000)
                logger.info(
                    "Task '%s' completed at iteration %d (%dms)",
                    task.id,
                    iteration,
                    elapsed,
                )
                out_payload = final.strip()
                accum_tools = _get_accumulated_tool_outputs()
                if accum_tools and accum_tools not in out_payload:
                    out_payload = f"{out_payload}\n\n{accum_tools}"

                if on_event:
                    on_event({
                        "type": "final_answer",
                        "task_id": task.id,
                        "answer": out_payload,
                    })
                return TaskResult(
                    task_id=task.id,
                    status=TaskStatus.COMPLETED,
                    output=out_payload,
                    tool_calls_made=tool_calls_made,
                    execution_time_ms=elapsed,
                )

            # ── Step 4: Handle implicit final answer ────────
            if tool_call is None:
                # If tools are required and not yet run, don't accept implicit answer early
                if tools and not tool_calls_made and iteration < (self.max_iterations - 1):
                    messages.append({"role": "assistant", "content": response})
                    steering_msg = self._build_tool_steering_message(task, tools, user_query)
                    messages.append({"role": "user", "content": steering_msg})
                    continue

                # Guardrail 4: IMPLICIT FINAL ANSWER
                elapsed = int((time.monotonic() - start_time) * 1000)
                logger.info(
                    "Task '%s' implicit final answer at iteration %d",
                    task.id,
                    iteration,
                )
                out_payload = response.strip()
                accum_tools = _get_accumulated_tool_outputs()
                if accum_tools and accum_tools not in out_payload:
                    out_payload = f"{out_payload}\n\n{accum_tools}".strip()
                elif not out_payload and accum_tools:
                    out_payload = accum_tools
                elif not out_payload:
                    out_payload = f"Task completed: {task.name}."

                if on_event:
                    on_event({
                        "type": "final_answer",
                        "task_id": task.id,
                        "answer": out_payload,
                    })
                return TaskResult(
                    task_id=task.id,
                    status=TaskStatus.COMPLETED,
                    output=out_payload,
                    tool_calls_made=tool_calls_made,
                    execution_time_ms=elapsed,
                )

            tool_name = tool_call.get("tool", "")
            tool_args = tool_call.get("args", {})
            tool_spec = tool_map.get(tool_name)
            tool_args = self._enrich_tool_args(
                tool_spec,
                tool_args,
                task,
                user_query,
                upstream_context,
                _get_accumulated_tool_outputs(),
            )

            # ── Guardrail 2: Validate tool exists ───────────
            if tool_name not in tool_map:
                logger.warning(
                    "Task '%s' hallucinated tool: '%s'",
                    task.id,
                    tool_name,
                )
                messages.append(
                    {"role": "assistant", "content": response}
                )
                messages.append(
                    {
                        "role": "user",
                        "content": (
                            f"Error: Tool '{tool_name}' does not exist. "
                            f"Available tools: {list(tool_map.keys())}. "
                            f"Use one of the listed tools or provide your "
                            f"FINAL_ANSWER."
                        ),
                    }
                )
                continue

            # ── Step 4: Execute tool ────────────────────────
            tool_spec = tool_map[tool_name]
            logger.debug(
                "Task '%s' calling tool '%s' with args: %s",
                task.id,
                tool_name,
                json.dumps(tool_args)[:200],
            )

            if on_event:
                on_event({
                    "type": "tool_start",
                    "task_id": task.id,
                    "tool": tool_name,
                    "args": tool_args,
                })

            try:
                call_args = self._inject_run_context(tool_spec, tool_args)
                result = await tool_spec.function(**call_args)
                result_str = str(result)

                # Guardrail 3: Cap output size
                if len(result_str) > self.max_output_chars:
                    result_str = (
                        result_str[: self.max_output_chars]
                        + "\n[...output truncated]"
                    )

                tool_calls_made.append(tool_name)

                if on_event:
                    on_event({
                        "type": "tool_end",
                        "task_id": task.id,
                        "tool": tool_name,
                        "output": result_str[:200],
                    })

            except TypeError as e:
                # Wrong arguments passed to tool
                result_str = (
                    f"Error: Invalid arguments for tool '{tool_name}': {e}. "
                    f"Check the parameter names and types."
                )
                logger.warning(
                    "Task '%s' tool '%s' argument error: %s",
                    task.id,
                    tool_name,
                    e,
                )

            except Exception as e:
                result_str = f"Error: Tool '{tool_name}' failed: {e}"
                logger.error(
                    "Task '%s' tool '%s' execution error: %s",
                    task.id,
                    tool_name,
                    e,
                )

            if on_heartbeat:
                try:
                    on_heartbeat()
                except Exception:
                    pass

            # ── Step 5: Append to conversation and loop ─────
            messages.append(
                {"role": "assistant", "content": response}
            )
            messages.append(
                {
                    "role": "user",
                    "content": (
                        f"Tool `{tool_name}` returned:\n\n"
                        f"{result_str}\n\n"
                        f"Analyze this result. Either call another tool "
                        f"or provide your FINAL_ANSWER."
                    ),
                }
            )

        # ── Guardrail 1: Max iterations reached ────────────
        elapsed = int((time.monotonic() - start_time) * 1000)
        logger.warning(
            "Task '%s' reached max iterations (%d). Forcing completion.",
            task.id,
            self.max_iterations,
        )

        # Return the last assistant message as the output
        last_assistant = ""
        for msg in reversed(messages):
            if msg["role"] == "assistant":
                last_assistant = msg["content"]
                break

        # If tools were executed, append tool results so real data is never lost
        tool_outputs_list: list[str] = []
        for msg in messages:
            if msg["role"] == "user" and " returned:\n\n" in msg["content"]:
                content = msg["content"]
                body = content.split(" returned:\n\n", 1)[1]
                if "\n\nAnalyze this result" in body:
                    body = body.split("\n\nAnalyze this result", 1)[0].strip()
                if body:
                    tool_outputs_list.append(body)
        accum_tools = "\n\n---\n\n".join(tool_outputs_list)

        output_content = last_assistant
        if accum_tools:
            output_content = f"{last_assistant}\n\n{accum_tools}".strip()

        return TaskResult(
            task_id=task.id,
            status=TaskStatus.COMPLETED,
            output=(
                f"[Reached max {self.max_iterations} iterations] "
                + output_content
            ),
            tool_calls_made=tool_calls_made,
            execution_time_ms=elapsed,
        )

    # ── Response Parsing ─────────────────────────────────────────

    def _extract_final_answer(self, response: str) -> str | None:
        """Check if the LLM produced an explicit final answer.

        Looks for:
          FINAL_ANSWER: <content>
          CANNOT_COMPLETE: <reason>
        """
        patterns = [
            r"(?:\*\*|###\s*)?(?:FINAL_ANSWER|FINAL\s+ANSWER|Final\s+Answer)(?:\*\*)?\s*:\s*(.+)",
            r"(?:\*\*|###\s*)?(?:CANNOT_COMPLETE|CANNOT\s+COMPLETE)(?:\*\*)?\s*:\s*(.+)",
        ]
        for pat in patterns:
            match = re.search(pat, response, re.IGNORECASE | re.DOTALL)
            if match:
                ans = match.group(1).strip()
                if ans:
                    return ans

        for marker in ("FINAL_ANSWER:", "CANNOT_COMPLETE:", "FINAL ANSWER:", "Final Answer:"):
            if marker in response:
                ans = response.split(marker, 1)[1].strip()
                if ans:
                    return ans
        return None

    def _compress_context_history(self, messages: list[dict[str, str]]) -> list[dict[str, str]]:
        """Sliding-window context compression for local LLM reliability.

        Preserves:
          - Immutable Anchors: System persona (messages[0]) and initial task spec (messages[1])
          - Working Horizon: The last assistant turn and last tool result in full fidelity

        Compresses:
          - Historical intermediate tool results (steps older than 1 turn) down to high-density summary stamps.
        """
        if len(messages) <= 6:
            return messages

        compressed = [messages[0], messages[1]]
        # Middle turns: from index 2 up to len(messages) - 2
        for i in range(2, len(messages) - 2):
            msg = messages[i]
            if msg.get("role") == "user" and " returned:\n\n" in msg.get("content", ""):
                m_tool = re.match(r"Tool `([^`]+)` returned:\n\n(.*)", msg["content"], re.DOTALL)
                if m_tool:
                    tool_name = m_tool.group(1)
                    body = m_tool.group(2)
                    if "\n\nAnalyze this result" in body:
                        body = body.split("\n\nAnalyze this result")[0].strip()
                    lines = [line.strip() for line in body.splitlines() if line.strip()]
                    summary_snippet = " | ".join(lines[:12])
                    # Evidence ids are the handles the agent needs to re-query
                    # detail later, so they survive compression verbatim.
                    if len(summary_snippet) > 900:
                        summary_snippet = summary_snippet[:900] + "..."
                    compact_content = (
                        f"Tool `{tool_name}` [Historical output compressed]: {summary_snippet}\n\n"
                        f"[Full detail remains retrievable — re-run the tool or use "
                        f"query_evidence/get_evidence with the EV ids above]"
                    )
                    compressed.append({"role": "user", "content": compact_content})
                    continue
            elif msg.get("role") == "assistant" and len(msg.get("content", "")) > 400:
                content = msg["content"]
                compact_content = content[:300].strip() + "\n[...prior thought summarized]"
                compressed.append({"role": "assistant", "content": compact_content})
                continue
            compressed.append(msg)

        # Append working horizon (last 2 messages) unmodified
        compressed.extend(messages[-2:])
        return compressed

    def _extract_task_path_or_default(self, task: Task, user_query: str = "") -> str:
        """Extract a filesystem path mentioned in the task or user_query, defaulting to current working directory."""
        combined_text = f"{task.name} {task.description} {user_query}"
        # Match Windows drive path e.g. "D:\Security-logs-test\...", "D:\ai_gpu", D:\
        m = re.search(r'([a-zA-Z]:\\[^"\'\s<>*?|]*)', combined_text)
        if m:
            clean = m.group(1).rstrip(",;.:)").strip('"').strip("'")
            if clean:
                return clean
        # Match Unix style path /path/to/logs
        m_unix = re.search(r'(/(?:[a-zA-Z0-9._-]+/)+[a-zA-Z0-9._-]+)', combined_text)
        if m_unix:
            clean_u = m_unix.group(1).rstrip(",;.:)").strip('"').strip("'")
            if clean_u:
                return clean_u
        m_drive = re.search(r'([a-zA-Z]:)', combined_text)
        if m_drive:
            return f"{m_drive.group(1)}\\"
        # Fallback to current working directory (cross-platform) instead of hardcoding D:\
        return os.getcwd()

    def _convert_tools_to_openai(self, tools: list[ToolSpec]) -> list[dict[str, Any]]:
        """Convert ToolSpec instances to OpenAI function calling schemas."""
        openai_tools = []
        for spec in tools:
            properties: dict[str, Any] = {}
            required: list[str] = []
            for param_name, param_def in spec.parameters.items():
                if isinstance(param_def, dict):
                    p_type = param_def.get("type", "string")
                    p_desc = param_def.get("description", "")
                    properties[param_name] = {"type": p_type, "description": p_desc}
                    if param_def.get("required", False):
                        required.append(param_name)
                else:
                    properties[param_name] = {"type": "string"}

            openai_tools.append({
                "type": "function",
                "function": {
                    "name": spec.name,
                    "description": spec.description,
                    "parameters": {
                        "type": "object",
                        "properties": properties,
                        "required": required,
                    },
                },
            })
        return openai_tools

    def _inject_run_context(
        self, tool_spec: ToolSpec | None, tool_args: dict[str, Any]
    ) -> dict[str, Any]:
        """Attach the hidden ``_run_id`` for tools that declare they need it.

        The run id is never advertised in the OpenAI tool schema, so the model
        can neither supply nor tamper with it. Any value the model *did* invent
        is overwritten here.
        """
        if tool_spec is None or not getattr(tool_spec, "needs_run_context", False):
            return tool_args

        call_args = dict(tool_args)
        call_args["_run_id"] = self.run_id
        return call_args

    def _enrich_tool_args(
        self,
        tool_spec: ToolSpec | None,
        tool_args: dict[str, Any],
        task: Task,
        user_query: str,
        upstream_context: dict[str, str] | None,
        accumulated_tool_outputs: str,
    ) -> dict[str, Any]:
        """Enrich tool arguments with task target path or upstream evidence if missing."""
        enriched = dict(tool_args)
        allowed_params = set(tool_spec.parameters.keys()) if tool_spec is not None else None
        detected_path = self._extract_task_path_or_default(task, user_query)

        # 1. Target path enrichment
        for key in ["target_path", "path", "directory", "dir_path", "log_dir", "file_path"]:
            if allowed_params is not None and key not in allowed_params:
                continue
            val = enriched.get(key)
            if not val or val in ("D:\\", "C:\\", ".", "./", "value", ""):
                if detected_path:
                    enriched[key] = detected_path

        # 2. Upstream evidence / alert text enrichment
        combined_evidence = ""
        if upstream_context:
            combined_evidence = "\n\n".join(upstream_context.values())
        if accumulated_tool_outputs:
            combined_evidence = f"{combined_evidence}\n\n{accumulated_tool_outputs}".strip()

        for key in ["alert_text", "evidence_text", "raw_evidence_text", "raw_evidence", "evidence", "log_text", "incident_data"]:
            if allowed_params is not None and key not in allowed_params:
                continue
            val = str(enriched.get(key, "")).strip()
            if not val or val in ("Investigating logs", "value", "") or len(val) < 20:
                if combined_evidence:
                    enriched[key] = combined_evidence
                elif detected_path:
                    enriched[key] = f"Investigating logs at {detected_path}"

        # 3. Target entity for containment actions
        for key in ["target_entity", "entity", "ip", "indicator"]:
            if allowed_params is not None and key not in allowed_params:
                continue
            val = str(enriched.get(key, "")).strip()
            if not val or val in ("value", "127.0.0.1", ""):
                m_ips = re.findall(r"\b(?:(?:25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\.){3}(?:25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\b", combined_evidence)
                ext_ips = [ip for ip in m_ips if not (ip.startswith("10.") or ip.startswith("192.168.") or ip.startswith("172.16.") or ip.startswith("127."))]
                if ext_ips:
                    enriched[key] = ext_ips[0]

        return enriched

    def _build_tool_steering_message(self, task: Task, tools: list[ToolSpec], user_query: str = "") -> str:
        """Build an imperative steering message forcing the LLM to output a valid tool call."""
        detected_path = self._extract_task_path_or_default(task, user_query)
        tool_names = [t.name for t in tools]
        examples = []
        for t in tools:
            args_example: dict[str, Any] = {}
            for pname in t.parameters:
                pname_lower = pname.lower()
                if "path" in pname_lower or "dir" in pname_lower or "folder" in pname_lower or "target" in pname_lower:
                    args_example[pname] = detected_path
                elif "drive" in pname_lower:
                    drive = os.path.splitdrive(detected_path)[0]
                    args_example[pname] = f"{drive}\\" if drive else os.path.abspath(os.sep)
                elif "command" in pname_lower or "cmd" in pname_lower:
                    args_example[pname] = f"dir \"{detected_path}\""
                elif "recursive" in pname_lower:
                    args_example[pname] = True
                elif "alert_text" in pname_lower or "raw_evidence" in pname_lower:
                    args_example[pname] = f"Investigating logs at {detected_path}"
            examples.append(json.dumps({"tool": t.name, "args": args_example}))

        examples_text = "\n".join(f"- `{ex}`" for ex in examples)
        return (
            f"You have NOT executed any tools yet. This task REQUIRES calling tools to gather real host system data.\n"
            f"Available tools: {', '.join(tool_names)}.\n"
            f"You are running directly on the host machine with full filesystem and environment access.\n"
            f"Do NOT provide general conversational text, apologies, or conclusions without running a tool first.\n\n"
            f"Execute a tool now by replying ONLY with a JSON tool call in this exact format:\n"
            f"{examples_text}\n\n"
            f"Output your JSON tool call now:"
        )

    def _extract_tool_call(self, response: str) -> dict | None:
        """Extract a tool call JSON from the LLM response.

        Handles common local LLM quirks:
        - Clean JSON on its own line: {"tool": "name", "args": {...}}
        - Python dict literal with single quotes: {'tool': 'name', 'args': {...}}
        - OpenAI tool call format: {"name": "name", "arguments": {...}}
        - LangChain ReAct format: {"action": "name", "action_input": {...}}
        - JSON wrapped in markdown code blocks
        - JSON embedded in surrounding text
        - ReAct style ACTION / ACTION INPUT format
        - Standalone Python code block when execute_python is expected
        - Function call syntax: tool_name(param="value")

        Returns:
            Dict with 'tool' and 'args' keys, or None if no tool call found.
        """
        # 1. Look for markdown code blocks containing json or dict
        code_block_match = re.search(r"```(?:json|python)?\s*(\{.*?\})\s*```", response, re.DOTALL)
        if code_block_match:
            candidate = code_block_match.group(1)
            try:
                parsed = json.loads(candidate)
                norm = self._normalize_tool_dict(parsed)
                if norm:
                    return norm
            except Exception:
                try:
                    parsed = ast.literal_eval(candidate)
                    norm = self._normalize_tool_dict(parsed)
                    if norm:
                        return norm
                except Exception:
                    pass

        # 2. Extract balanced JSON object from response
        start_idx = 0
        while True:
            brace_start = response.find("{", start_idx)
            if brace_start == -1:
                break
            depth = 0
            in_str = False
            escape = False
            for j in range(brace_start, len(response)):
                ch = response[j]
                if escape:
                    escape = False
                    continue
                if ch == "\\":
                    escape = True
                    continue
                if ch == '"':
                    in_str = not in_str
                    continue
                if not in_str:
                    if ch == "{":
                        depth += 1
                    elif ch == "}":
                        depth -= 1
                        if depth == 0:
                            candidate = response[brace_start : j + 1]
                            try:
                                parsed = json.loads(candidate)
                                norm = self._normalize_tool_dict(parsed)
                                if norm:
                                    return norm
                            except Exception:
                                try:
                                    parsed = ast.literal_eval(candidate)
                                    norm = self._normalize_tool_dict(parsed)
                                    if norm:
                                        return norm
                                except Exception:
                                    pass
                            break
            start_idx = brace_start + 1

        # 3. ReAct style format: ACTION: <tool_name>\n[ACTION INPUT:] {"arg": val}
        action_match = re.search(r"ACTION:\s*([a-zA-Z0-9_\-]+)", response, re.IGNORECASE)
        if action_match:
            tool_name = action_match.group(1).strip()
            remainder = response[action_match.end():]
            json_match = re.search(r"(\{.*?\})", remainder, re.DOTALL)
            if json_match:
                try:
                    args = json.loads(json_match.group(1))
                    if isinstance(args, dict):
                        return {"tool": tool_name, "args": args}
                except Exception:
                    try:
                        args = ast.literal_eval(json_match.group(1))
                        if isinstance(args, dict):
                            return {"tool": tool_name, "args": args}
                    except Exception:
                        pass
            return {"tool": tool_name, "args": {}}

        # 4. If LLM generated a ```python ... ``` block directly
        py_match = re.search(r"```(?:python|py)\s*\n(.*?)```", response, re.DOTALL)
        if py_match:
            code_content = py_match.group(1).strip()
            if code_content and ("print(" in code_content or "def " in code_content or "import " in code_content or "sum(" in code_content):
                return {"tool": "execute_python", "args": {"code": code_content}}

        # 5. Function call syntax: tool_name(param="value", ...) or tool_name({"param": "value"})
        call_match = re.search(r"(?:call\s+|run\s+)?([a-zA-Z0-9_]+)\s*\((.*?)\)", response, re.DOTALL)
        if call_match:
            cand_tool = call_match.group(1).strip()
            inner = call_match.group(2).strip()
            # If inner is JSON dict
            if inner.startswith("{") and inner.endswith("}"):
                try:
                    parsed_args = json.loads(inner)
                    if isinstance(parsed_args, dict):
                        return {"tool": cand_tool, "args": parsed_args}
                except Exception:
                    try:
                        parsed_args = ast.literal_eval(inner)
                        if isinstance(parsed_args, dict):
                            return {"tool": cand_tool, "args": parsed_args}
                    except Exception:
                        pass
            # Parse kwargs like key="val", key='val', or key=123
            kw_matches = re.findall(r'([a-zA-Z0-9_]+)\s*=\s*(?:"([^"]*)"|\'([^\']*)\'|([a-zA-Z0-9_\.\\/:]+))', inner)
            if kw_matches:
                args = {}
                for k, v1, v2, v3 in kw_matches:
                    val: Any = v1 or v2 or v3
                    if str(val).lower() == "true":
                        val = True
                    elif str(val).lower() == "false":
                        val = False
                    elif str(val).isdigit():
                        val = int(val)
                    elif isinstance(val, str):
                        val = val.replace("\\\\", "\\")
                    args[k] = val
                return {"tool": cand_tool, "args": args}
            # Positional single string arg: tool_name("D:\ai_gpu")
            pos_match = re.match(r'^(?:"([^"]*)"|\'([^\']*)\')$', inner)
            if pos_match:
                single_val = pos_match.group(1) or pos_match.group(2)
                if isinstance(single_val, str):
                    single_val = single_val.replace("\\\\", "\\")
                return {
                    "tool": cand_tool,
                    "args": {
                        "path": single_val,
                        "directory_path": single_val,
                        "file_path": single_val,
                        "command": single_val,
                    },
                }

        return None

    def _normalize_tool_dict(self, parsed: Any) -> dict | None:
        """Normalize various tool call formats to {'tool': str, 'args': dict}."""
        if not isinstance(parsed, dict):
            return None

        # Standard: {"tool": "name", "args": {...}}
        if "tool" in parsed:
            raw_args = parsed.get("args", {})
            if isinstance(raw_args, str):
                try:
                    raw_args = json.loads(raw_args)
                except Exception:
                    try:
                        raw_args = ast.literal_eval(raw_args)
                    except Exception:
                        raw_args = {"input": raw_args}
            return {"tool": str(parsed["tool"]), "args": raw_args if isinstance(raw_args, dict) else {}}

        # OpenAI format: {"name": "name", "arguments" | "parameters": {...}}
        if "name" in parsed and any(k in parsed for k in ("arguments", "parameters", "args", "input")):
            tool_name = str(parsed["name"])
            raw_args = (
                parsed.get("arguments")
                or parsed.get("parameters")
                or parsed.get("args")
                or parsed.get("input")
                or {}
            )
            if isinstance(raw_args, str):
                try:
                    raw_args = json.loads(raw_args)
                except Exception:
                    try:
                        raw_args = ast.literal_eval(raw_args)
                    except Exception:
                        raw_args = {"input": raw_args}
            return {"tool": tool_name, "args": raw_args if isinstance(raw_args, dict) else {}}

        # LangChain / ReAct: {"action": "name", "action_input": {...}}
        if "action" in parsed and "action_input" in parsed:
            tool_name = str(parsed["action"])
            raw_args = parsed.get("action_input", {})
            if isinstance(raw_args, str):
                try:
                    raw_args = json.loads(raw_args)
                except Exception:
                    try:
                        raw_args = ast.literal_eval(raw_args)
                    except Exception:
                        raw_args = {"input": raw_args}
            return {"tool": tool_name, "args": raw_args if isinstance(raw_args, dict) else {}}

        return None
